import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1200, height: 900 }, locale: 'bn-BD', acceptDownloads: true });
const page = await context.newPage();
page.on('console', (m) => console.log('console', m.type(), m.text()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('download', (d) => console.log('download event', d.suggestedFilename()));
const base = 'http://127.0.0.1:4173';
await page.goto(base + '/', { waitUntil: 'networkidle' });
await page.getByLabel('আপনার নাম').fill('পরীক্ষা ব্যবহারকারী');
await page.getByRole('button', { name: 'শুরু করুন' }).click();
await page.locator('h1').first().waitFor();
await page.getByRole('button', { name: 'নতুন খরচ' }).first().click();
await page.locator('#expense-category').selectOption({ label: 'যাতায়াত' });
await page.getByLabel('কোথা থেকে').fill('ঢাকা');
await page.getByLabel('কোথায়').fill('গাজীপুর');
await page.getByLabel('মাধ্যম').selectOption({ label: 'বাস' });
await page.getByLabel('কতজন').fill('2');
await page.getByLabel('উদ্দেশ্য').fill('অফিসের কাজে সভায় যাওয়া');
await page.locator('#expense-total').fill('150');
await page.getByRole('button', { name: 'খরচ যোগ করুন', exact: true }).click();
await page.getByText('নতুন খরচ যোগ হয়েছে।').waitFor();
await page.getByRole('link', { name: 'খরচের হিসাব' }).first().click();
await page.getByRole('heading', { name: 'খরচের খাতা' }).waitFor();
const row = page.locator('tbody tr').filter({ hasText: 'ঢাকা' });
await row.first().getByRole('link', { name: /ভাউচার দেখুন/ }).click();
await page.getByRole('heading', { name: 'A5 ভাউচার' }).waitFor();
await page.screenshot({ path: '/tmp/mv2-focused-before-pdf.png', fullPage: true });
const button = page.getByRole('button', { name: 'PDF ডাউনলোড' });
console.log('button enabled', await button.isEnabled());
const downloadPromise = page.waitForEvent('download', { timeout: 45000 }).catch((e) => { console.log('no download', e.message); return null; });
await button.click();
console.log('clicked');
await page.waitForTimeout(3000);
console.log('toast', await page.locator('[role="status"], [role="alert"]').allInnerTexts());
const download = await downloadPromise;
console.log('download?', Boolean(download), download?.suggestedFilename());
if (download) await download.saveAs('/tmp/mv2-focused.pdf');
console.log('done');
await browser.close();
